function catOf(input = {}, p = {}) {
  let cat = p.cat || 'default';
  const text = [input.name, input.category, input.sellingPoints, p.name, p.formLabel].filter(Boolean).join(' ');
  // 1) 语义覆写（表格见 CAT_OVERRIDES，文档 §3.1 由它生成）
  for (const o of CAT_OVERRIDES) {
    if (o.only && cat !== o.only) continue;
    if (!o.re.test(text)) continue;
    if (o.and && !o.and.test(text)) continue;
    cat = o.cat;
  }
  // 2) 贴纸类按用途分：车贴是汽车用品，纹身贴是彩妆，冰箱贴/墙贴是家居，其余是文具
  if (/车贴|车身贴|拉花/.test(text)) cat = 'car';
  else if (/纹身贴|身体贴|临时贴/.test(text)) cat = 'beauty';
  else if (/冰箱贴|墙贴|壁画/.test(text)) cat = 'home';
  // 3) 还是认不出来，才按商品名兜底推品类
  if (cat === 'default') {
    for (const h of CAT_HINTS) { if (h.re.test(text)) { cat = h.cat; break; } }
  }
  return cat;
}

