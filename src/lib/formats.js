function purposeOf(input = {}, p = {}) {
  // 商品级覆写最准（睡袋的 purpose 是 REFINE 写死的），先用它
  if (p && p.purpose) return p.purpose;
  const base = [input.name, input.category, p.name, p.core, p.formLabel].filter(Boolean).join(' ');
  for (const x of PURPOSE_HINTS) {
    if (x.re.test(base)) return x.what;
  }
  // 名字里看不出来时才拿卖点当线索：卖点里的「保温」「防水」很容易把用途带到别的品类上
  const withSell = base + ' ' + (input.sellingPoints || '');
  if (withSell.trim() !== base.trim()) {
    for (const x of PURPOSE_HINTS) {
      if (x.re.test(withSell)) return x.what;
    }
  }
  return '';
}

