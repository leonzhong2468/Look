function pickFormat(input = {}, variant = 0) {
  // 用户在界面上指定了形态：直接用，不再按分数改主意（重抽也保持这个形态，
  // 但文案/场景会随 variant 换一套，仍然是新片子）
  if (input.formatKey === 'free') return buildFree(input, variant);
  if (input.formatKey) {
    const chosen = FORMATS.find(f => f.key === input.formatKey);
    if (chosen) return chosen;
  }
  const ranked = rankFormats(input);
  const pool = ranked.slice(0, 3);
  const n = Math.abs(parseInt(variant, 10) || 0);
  return pool[n % pool.length] || FORMATS[0];
}

function cameraOf(format) {
  return CAMERA_SETS[(format && format.energy) || 'fast'] || CAMERA_SETS.fast;
}

/** 形态的「为什么是它」一句话，写进提示词让模型明白创作意图 */
function whyOf(format, ctx) {
  const hook = (ctx && (ctx.sell1 || ctx.sell2)) ? `；本次重点让「${ctx.sell1 || ctx.sell2}」在画面里成立` : '';
  return (format.why || '') + hook;
}

