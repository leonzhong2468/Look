function fill(tpl, ctx) {
  const c = ctx || {};
  return String(tpl || '').replace(/\{(\w+)\}/g, (m, k) => {
    const v = c[k];
    if (v != null && v !== '') return String(v);
    return CTX_FALLBACK[k] != null ? CTX_FALLBACK[k] : '';
  });
}

/**
 * 给 14 种形态打分：品类 >> 卖点关键词 > 商品名关键词 > 默认优先级。
 * 返回按分数倒序的形态数组（同分时按 CAT_ORDER 的顺序）。
 */
function rankFormats(input = {}) {
  let p = {};
  // 先纠偏再打分：睡袋被商品库认成「帐篷/露营装备」时，不纠正就会推荐旅拍、硬核实测
  try { p = refineProduct(productLib.analyze(input), input) || {}; } catch (e) { p = {}; }
  const text = [
    input.name, input.category, input.sellingPoints, input.audience,
    p.name, p.cat, p.catLabel, p.form, p.formLabel, p.core
  ].filter(Boolean).join(' ');

  // 品类：先信 product.js 的形态库，认不出来再走 CAT_HINTS 兜底（全类目覆盖）
  const cat = catOf(input, p);
  const order = CAT_ORDER[cat] || CAT_ORDER.default;

  const scored = FORMATS.map(f => {
    let s = 0;
    const oi = order.indexOf(f.key);
    if (oi >= 0) s += 12 - oi * 2;                 // 品类首选最高
    if (f.cats.includes(cat)) s += 3;
    if (f.keywords && f.keywords.test(text)) s += 5;
    const boost = BOOST[f.key];
    if (boost && boost.re.test(text)) s += boost.w;
    // 泳装类的最佳场景就是海边/泳池：旅拍优先，穿搭型录退一位
    if (/泳装|泳衣|比基尼/.test(text)) {
      // 泳装的天然场景就是海边/泳池：旅拍必须压过穿搭型录（ootd 的「显瘦」加权会抢分）
      if (f.key === 'travel') s += 12;
      if (f.key === 'ootd') s -= 6;
    }
    // 品类偏好微调 + 个别商品的固定拍法
    const tune = TUNE[cat];
    if (tune && tune[f.key]) s += tune[f.key];
    for (const pt of PRODUCT_TUNE) {
      if (pt.not && pt.not.test(text)) continue;      // 已纠偏的商品不再吃这条加权
      if (pt.re.test(text) && pt.tune[f.key]) s += pt.tune[f.key];
    }
    const avoid = AVOID[f.key];
    if (avoid && avoid.test(text)) s -= 25;
    return { f, s, oi: oi >= 0 ? oi : 99 };
  });
  scored.sort((a, b) => b.s - a.s || a.oi - b.oi);
  return scored.map(x => x.f);
}

