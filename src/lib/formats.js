function conceive(input = {}, variant = 0) {
  let p = {};
  // 和 buildPlan 用同一份纠偏结果，麻烦与场景才不会被商品的错误归类带偏
  try { p = refineProduct(productLib.analyze(input), input) || {}; } catch (e) { p = {}; }
  const text = [
    input.name, input.category, input.sellingPoints, input.audience,
    p.name, p.cat, p.catLabel, p.form, p.formLabel, p.core
  ].filter(Boolean).join(' ');
  // 和 rankFormats 共用一套品类判断（含 CAT_HINTS 兜底），两处不会再打架
  const cat = catOf(input, p);

  const n = Math.abs(parseInt(variant, 10) || 0);

  // 麻烦：按卖点关键词命中数排序，命中越多越贴身
  const scored = TROUBLE.map(t => {
    const g = text.match(new RegExp(t.re.source, 'g'));
    return { t, s: g ? g.length : 0 };
  });
  scored.sort((a, b) => b.s - a.s);
  let trouble;
  if (scored[0].s > 0) trouble = scored[0].t;
  else {
    const byCat = TROUBLE_BY_CAT[cat];
    trouble = (byCat && TROUBLE.find(t => t.name === byCat)) || TROUBLE[n % TROUBLE.length];
  }

  // 场景：商品级偏好 > 麻烦能发生的地方 > 品类适配
  let pool = [];
  const pref = MOTIF_PREFER.find(x => x.re.test(text));
  if (pref) pool = pref.motifs.map(k => MOTIFS.find(m => m.key === k)).filter(Boolean);
  if (!pool.length) {
    pool = (TROUBLE_MOTIF[trouble.name] || [])
      .map(k => MOTIFS.find(m => m.key === k)).filter(Boolean);
  }
  const catOk = pool.filter(m => (m.cats || []).includes(cat));
  if (catOk.length) pool = catOk;
  if (!pool.length) pool = MOTIFS.filter(m => (m.cats || []).includes(cat));
  if (!pool.length) pool = MOTIFS;

  // 商品级覆写优先：某些商品的麻烦跟品类通用麻烦不是一回事（睡袋 ≠ 冲奶粉）
  if (p.trouble && typeof p.trouble === 'object' && p.trouble.name) {
    trouble = p.trouble;
    const tm = TROUBLE_MOTIF[trouble.name];
    if (tm) {
      const again = tm.map(k => MOTIFS.find(m => m.key === k)).filter(Boolean);
      const okCat = again.filter(m => (m.cats || []).includes(cat));
      if (okCat.length) pool = okCat;
      else if (again.length) pool = again;
    }
  }

  const motif = pool[n % pool.length];
  return { p, cat, motif, trouble, text };
}

