function refineProduct(p, input = {}) {
  const base = p || {};
  const text = [input.name, input.category, input.sellingPoints, base.name, base.core, base.formLabel].filter(Boolean).join(' ');
  for (const r of REFINE) {
    if (r.test.test(text)) {
      return Object.assign({}, base, r.patch, { refined: true });
    }
  }
  return Object.assign({}, base, { refined: false });
}

