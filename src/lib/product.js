function scoreCats(input) {
  const name = String(input.name || '');
  const cat = String(input.category || '');
  const sell = String(input.sellingPoints || '');
  const all = [name, cat, sell].join(' ');
  for (const L of CAT_LOCK) {
    if (L.not && L.not.test(all)) continue;
    if (L.re.test(all)) {
      const r = CAT_RULES.find(x => x.key === L.key);
      if (r) return { key: r.key, label: r.label, score: 30, first: 0 };
    }
  }
  let best = null;
  for (const r of CAT_RULES) {
    let score = 0, first = 1e9;
    const weak = r.weak || [];
    for (const w of r.words) {
      const wScore = weak.indexOf(w) >= 0 ? 1 : (2 + Math.min(3, w.length));
      const iName = name.indexOf(w);
      if (iName >= 0) { score += wScore; first = Math.min(first, iName); }
      if (cat.indexOf(w) >= 0) score += 3;
      if (sell.indexOf(w) >= 0) score += 1;
    }
    if (score > 0 && (!best || score > best.score || (score === best.score && first < best.first))) {
      best = { key: r.key, label: r.label, score, first };
    }
  }
  return best || { key: 'default', label: '通用商品', score: 0, first: 1e9 };
}

