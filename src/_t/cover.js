const fail = [];
let n = 0;

for (const [name, category, sellingPoints] of SAMPLES) {
  n++;
  const r = P.buildPrompt({ name, category, sellingPoints, duration: 15, ratio: '9:16', noText: true, noVoice: true });
  const txt = r.full || '';
  const cat = (txt.match(/· 品类与形态：(.+)/) || [])[1] || '';
  const form = (txt.match(/【本条片子的形态：([^】]+)】/) || [])[1] || '';
  const beats = (txt.match(/^\d+%-\d+%/gm) || []).length;
  const hasName = txt.includes('· 商品：' + name);
  const hasScene = /· 场景：|· 指定场景：/.test(txt);
  const hasBan = /【约束条件】/.test(txt);

  const errs = [];
  if (!cat || /通用商品/.test(cat)) errs.push('未识别品类');
  if (!hasName) errs.push('商品名没写进正文');
  if (!form) errs.push('没有形态');
  if (beats !== 8) errs.push(`节拍数=${beats}`);
  if (!hasScene) errs.push('没有场景');
  if (!hasBan) errs.push('没有约束条件');
  if (errs.length) fail.push(`${name}（${category}）：${errs.join('、')} → ${cat}`);
}

// 「其他视频」四种请求
const kindErr = [];
for (const k of ['t2i', 't2v', 'i2i', 'i2v']) {
  const o = P.buildOtherRequest({ videoKind: k, prompt: '一只猫在窗台上看雨', duration: 10, ratio: '9:16' });
  if (!o.request || o.kindKey !== k) kindErr.push(k + ' 组装失败');
  if (['i2i', 'i2v'].includes(k) && !o.needRef) kindErr.push(k + ' 应该要求参考图');
  if (['t2i', 't2v'].includes(k) && o.needRef) kindErr.push(k + ' 不该要求参考图');
}

console.log(`全类目回归：${n} 个商品样本`);
console.log(`  未识别 / 结构缺失：${fail.length}`);
if (fail.length) { for (const f of fail) console.log('  ✗ ' + f); }
console.log(`其他视频四种请求：${kindErr.length ? '有 ' + kindErr.length + ' 个问题' : '全部正常'}`);
for (const e of kindErr) console.log('  ✗ ' + e);

const bad = fail.length + kindErr.length;
console.log(bad === 0 ? '\n通过（未识别品类 = 0）' : `\n失败 ${bad} 项`);
process.exit(bad === 0 ? 0 : 1);
